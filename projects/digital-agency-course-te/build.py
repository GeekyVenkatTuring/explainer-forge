# ---------------------------------------------------------------- TTS + build machinery
def ffdur(path):
    out = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                          "-of", "default=noprint_wrappers=1:nokey=1", path],
                         capture_output=True, text=True, check=True)
    return round(float(out.stdout.strip()), 3)


def tts_chunk(path, text):
    mp3 = path[:-4] + ".mp3"
    subprocess.run(["edge-tts", "--voice", VOICE, f"--rate={RATE}", "--text", text,
                    "--write-media", mp3], check=True, capture_output=True)
    subprocess.run(["ffmpeg", "-y", "-i", mp3, "-ar", "24000", "-ac", "1", path],
                   check=True, capture_output=True)
    os.remove(mp3)


def gen_one(seg_id, text):
    fin = os.path.join(FIN, seg_id + ".wav")
    if os.path.exists(fin):
        return fin, ffdur(fin)
    chunks = [c.strip() for c in text.split("[pause]") if c.strip()]
    paths = []
    for ci, chunk in enumerate(chunks):
        cp = os.path.join(RAW, f"{seg_id}_c{ci}.wav")
        if not os.path.exists(cp):
            tts_chunk(cp, chunk)
        paths.append(cp)
    psil = os.path.join(RAW, "_pause.wav")
    if not os.path.exists(psil):
        subprocess.run(["ffmpeg", "-y", "-f", "lavfi", "-i", "anullsrc=r=24000:cl=mono",
                        "-t", str(PAUSE), psil], check=True, capture_output=True)
    clist = os.path.join(RAW, f"{seg_id}_concat.txt")
    with open(clist, "w") as f:
        for i2, p2 in enumerate(paths):
            f.write(f"file '{p2}'\n")
            if i2 < len(paths) - 1:
                f.write(f"file '{psil}'\n")
    subprocess.run(["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", clist,
                    "-c", "copy", fin], check=True, capture_output=True)
    return fin, ffdur(fin)


def caption_cues(text, start, end):
    clean = re.sub(r"\s+", " ", text.replace("[pause]", " ")).strip()
    parts = re.split(r"(?<=[.?!])\s+", clean)
    cues = []
    for pt in parts:
        pt = pt.strip()
        if not pt:
            continue
        if len(pt) > 60 and ("," in pt or "—" in pt):
            buf = ""
            for s in re.split(r"(?<=[,—])\s+", pt):
                if len(buf) + len(s) > 60 and buf:
                    cues.append(buf.strip()); buf = s
                else:
                    buf = (buf + " " + s).strip()
            if buf:
                cues.append(buf.strip())
        else:
            cues.append(pt)
    total = sum(len(c) for c in cues) or 1
    span, out, t = end - start, [], start
    for c in cues:
        d = span * (len(c) / total)
        out.append([round(t, 3), round(t + d, 3), c]); t += d
    if out:
        out[-1][1] = round(end, 3)
    return out


def build_chapter(ch):
    segs = CHAPTERS[ch]
    manifest = []
    for sid, variant, props, text in segs:
        path, dur = gen_one(sid, text)
        manifest.append({"id": sid, "variant": variant, "props": props, "wav": path,
                         "duration": dur, "narration": text})
        warn = "  ⚠ LONG >90s" if dur > 90 else ""
        print(f"  {sid:14s} {dur:6.2f}s{warn}", flush=True)
    silence = os.path.join(FIN, "_sil.wav")
    if not os.path.exists(silence):
        subprocess.run(["ffmpeg", "-y", "-f", "lavfi", "-i", "anullsrc=r=24000:cl=mono",
                        "-t", str(GAP), silence], check=True, capture_output=True)
    clist = os.path.join(ROOT, f"concat_{ch}.txt")
    with open(clist, "w") as f:
        for i, m in enumerate(manifest):
            f.write(f"file '{m['wav']}'\n")
            if i < len(manifest) - 1:
                f.write(f"file '{silence}'\n")
    subprocess.run(["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", clist,
                    "-c", "copy", os.path.join(PUBLIC, f"{ch}.wav")], check=True, capture_output=True)
    cuts, cues, t = [], [], 0.0
    for m in manifest:
        start, end = t, t + m["duration"]
        cuts.append({"id": m["id"], "type": m["variant"], "in_seconds": round(start, 3),
                     "out_seconds": round(end, 3),
                     "props": {**m["props"], "dur": round(m["duration"] + GAP, 3)}})
        cues.extend(caption_cues(m["narration"], start, end))
        t = end + GAP
    props = {"cuts": cuts, "captions": cues,
             "audio": {"narration": {"src": f"{PREFIX}/{ch}.wav", "volume": 1.0}}}
    json.dump(props, open(os.path.join(ROOT, "artifacts", f"{ch}.json"), "w"),
              ensure_ascii=False, indent=2)
    print(f"{ch}: total {t - GAP:.2f}s ({(t-GAP)/60:.2f} min), {len(cuts)} scenes, {len(cues)} cues")


def build_master():
    """Concatenate rendered chapter mp4s (in chapter order) -> renders/master.mp4."""
    rd = os.path.join(ROOT, "renders")
    chs = [c for c in CHAPTERS.keys() if os.path.exists(os.path.join(rd, f"{c}.mp4"))]
    if not chs:
        print("no chapter mp4s found in renders/ — render chapters first"); return
    lst = os.path.join(rd, "_master_concat.txt")
    with open(lst, "w") as f:
        for c in chs:
            f.write(f"file '{os.path.join(rd, c + '.mp4')}'\n")
    out = os.path.join(rd, "master.mp4")
    subprocess.run(["ffmpeg", "-y", "-f", "concat", "-safe", "0", "-i", lst,
                    "-c:v", "libx264", "-preset", "medium", "-crf", "18",
                    "-c:a", "aac", "-b:a", "192k", out], check=True)
    print(f"master.mp4 built from {len(chs)} chapters: {', '.join(chs)}  ({ffdur(out)/60:.1f} min)")


